"""Generates a C++ source file embedding binary files as 256-byte aligned arrays, and a table
mapping their names (file names without extension) to their data.

Usage:
  embed_files.py -o output.cpp -n table_function_name file1 file2 ...
"""

import argparse
import os
import struct


def main():
  parser = argparse.ArgumentParser(description='Embeds binary files in a C++ source file.')
  parser.add_argument('files', nargs='*')
  parser.add_argument('-o', '--output', required=True)
  parser.add_argument('-n', '--name', required=True, help='name of the generated lookup function')
  args = parser.parse_args()

  lines = ['// Generated by embed_files.py, do not edit', '',
           '#include <cstddef>', '#include <cstdint>', '#include <cstring>', '',
           'namespace vkoidn {', '', 'namespace {', '']
  entries = []

  for i, path in enumerate(args.files):
    data = open(path, 'rb').read()
    name = os.path.splitext(os.path.basename(path))[0]
    # Pad to 8 bytes and emit 64-bit words (much faster to compile than bytes)
    padded = data + b'\0' * (-len(data) % 8)
    words = struct.unpack('<%dQ' % (len(padded) // 8), padded)
    lines.append('alignas(256) static const uint64_t embedded%d[%d] = {' % (i, max(len(words), 1)))
    for j in range(0, len(words), 8):
      lines.append(','.join('0x%x' % w for w in words[j:j+8]) + ',')
    lines.append('};')
    lines.append('')
    entries.append((name, i, len(data)))

  lines.append('struct EmbeddedFile { const char* name; const void* data; size_t size; };')
  lines.append('')
  lines.append('static const EmbeddedFile embeddedFiles[] = {')
  for name, i, size in entries:
    lines.append('  {"%s", embedded%d, %d},' % (name, i, size))
  lines.append('  {nullptr, nullptr, 0}')
  lines.append('};')
  lines.append('')
  lines.append('} // namespace')
  lines.append('')
  lines.append('// Returns the embedded file with the specified name (nullptr if not found)')
  lines.append('const void* %s(const char* name, size_t* size)' % args.name)
  lines.append('{')
  lines.append('  for (const EmbeddedFile* f = embeddedFiles; f->name; ++f)')
  lines.append('  {')
  lines.append('    if (strcmp(f->name, name) == 0)')
  lines.append('    {')
  lines.append('      if (size) *size = f->size;')
  lines.append('      return f->data;')
  lines.append('    }')
  lines.append('  }')
  lines.append('  return nullptr;')
  lines.append('}')
  lines.append('')
  lines.append('} // namespace vkoidn')
  lines.append('')

  os.makedirs(os.path.dirname(os.path.abspath(args.output)), exist_ok=True)
  content = '\n'.join(lines)
  # Only write if changed to avoid needless recompilation
  if not os.path.exists(args.output) or open(args.output).read() != content:
    with open(args.output, 'w') as f:
      f.write(content)


if __name__ == '__main__':
  main()
